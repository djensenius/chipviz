#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn alphabet_glyphs_are_drawn_distinct_and_fit_the_cell() {
        for (index, &character) in ALPHABET.iter().enumerate() {
            let bits = glyph(character).unwrap_or_else(|| panic!("{character} has no glyph"));
            assert!(bits != 0 && bits & !FULL == 0, "{character}");
            for &other in &ALPHABET[..index] {
                assert_ne!(glyph(other), Some(bits), "{character} looks like {other}");
            }
        }
    }

    #[test]
    fn accents_sit_on_row_zero_above_the_base_letter() {
        let row0 = (1u64 << 5) - 1;
        let a = glyph('A').unwrap();
        assert_eq!(a & row0, 0);
        for accented in ['Á', 'À', 'Â', 'Ä', 'Ã'] {
            let bits = glyph(accented).unwrap();
            assert_eq!(bits & !row0, a, "{accented}");
            assert_ne!(bits & row0, 0, "{accented}");
        }
        assert_eq!(glyph('Й').unwrap() & !row0, glyph('И').unwrap());
        assert_eq!(glyph('Ź').unwrap() & !row0, glyph('Z').unwrap());
        assert_eq!(glyph(' '), Some(0));
        assert_eq!(glyph('🙂'), None);
        assert_eq!(glyph('字'), None);
        assert_eq!(glyph('a'), None, "lowercase Latin is not drawn");
    }

    #[test]
    fn column_zero_is_the_left_edge() {
        // 'L' is lit down its left column and along its bottom row.
        let bits = glyph('L').unwrap();
        assert!((1..8).all(|row| bits >> (row * 5) & 1 == 1));
        assert_eq!(bits >> 35, 0b11111);
        assert_eq!(bits >> 5 & 0b11110, 0);
    }
}

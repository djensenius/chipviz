pub fn cell_pixel(cell: Option<Cell>, x: usize, y: usize) -> [u8; 4] {
    assert!(x < 8 && y < 8);
    let Some(cell) = cell else {
        return UNKNOWN;
    };
    let row = match cell.code {
        32 => 0,
        81..=88 => RAYS[usize::from(cell.code - 81)][y],
        96..=111 => FIELD[usize::from(cell.code - 96)][y],
        code => panic!("unexpected oracle code {code}"),
    };
    if row & (0x80 >> x) == 0 {
        BACKGROUND
    } else {
        COLOURS[usize::from(cell.colour)]
    }
}

pub fn field_pixel(field: &PetsciiMeterField, x: u32, y: u32) -> [u8; 4] {
    assert!(x < 320 && y < 200);
    cell_pixel(
        field.cell((x / 8) as usize, (y / 8) as usize),
        (x % 8) as usize,
        (y % 8) as usize,
    )
}
